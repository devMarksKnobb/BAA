import path from "node:path";
import { writeFile, mkdir } from "node:fs/promises";
import type { MigrationGraph } from "../types/graph.js";
import type { Degradation } from "../types/degradation.js";
import type { WriteResult } from "./writer.js";

export interface MigrationReport {
  summary: {
    pages: number;
    databases: number;
    databaseRows: number;
    attachments: number;
    totalTimeMs: number;
    outputSizeBytes: number;
  };
  execution: {
    mode: "write" | "dry-run";
    filesWritten: number;
  };
  degradations: Array<{
    tag: string;
    count: number;
    severity: string;
    samples: string[];
  }>;
  unresolvedLinks: Array<{
    href: string;
    context: string;
    reason: string;
  }>;
}

/**
 * Stage 6: Generate migration report.
 */
export async function generateReport(
  graph: MigrationGraph,
  writeResult: WriteResult,
  allDiagnostics: Degradation[],
  outputDir: string,
  startedAt: number,
): Promise<MigrationReport> {
  // Count node types
  let pages = 0;
  let databases = 0;
  let databaseRows = 0;
  let attachments = 0;

  for (const [, node] of graph.nodes) {
    switch (node.kind) {
      case "page": pages++; break;
      case "database": databases++; break;
      case "database-row": databaseRows++; break;
      case "attachment": attachments++; break;
    }
  }

  // Group degradations by tag
  const degradationMap = new Map<
    string,
    { tag: string; count: number; severity: string; samples: string[] }
  >();
  for (const d of allDiagnostics) {
    const existing = degradationMap.get(d.tag);
    if (existing) {
      existing.count++;
      if (existing.samples.length < 3) {
        existing.samples.push(d.location);
      }
    } else {
      degradationMap.set(d.tag, {
        tag: d.tag,
        count: 1,
        severity: d.severity,
        samples: [d.location],
      });
    }
  }

  // Collect unresolved links
  const unresolvedLinks: MigrationReport["unresolvedLinks"] = [];
  for (const [, node] of graph.nodes) {
    if (node.kind === "unresolved") {
      unresolvedLinks.push({
        href: node.originalHref,
        context: node.context,
        reason: node.reason,
      });
    }
  }
  // Also from edges
  for (const edge of graph.edges) {
    if (edge.toId === null && edge.type !== "external") {
      unresolvedLinks.push({
        href: edge.originalHref,
        context: edge.fromId,
        reason: "unresolved",
      });
    }
  }

  const report: MigrationReport = {
    summary: {
      pages,
      databases,
      databaseRows,
      attachments,
      totalTimeMs: Date.now() - startedAt,
      outputSizeBytes: writeResult.bytesWritten,
    },
    execution: {
      mode: writeResult.mode,
      filesWritten: writeResult.filesWritten,
    },
    degradations: [...degradationMap.values()].sort((a, b) =>
      a.tag.localeCompare(b.tag),
    ),
    unresolvedLinks,
  };

  // Write report files
  const resolvedOutputDir = path.resolve(outputDir);
  await mkdir(resolvedOutputDir, { recursive: true });

  const jsonPath = path.join(resolvedOutputDir, "report.json");
  await writeFile(jsonPath, JSON.stringify(report, null, 2), "utf-8");

  const mdPath = path.join(resolvedOutputDir, "report.md");
  await writeFile(mdPath, formatReportMd(report), "utf-8");

  return report;
}

function formatReportMd(report: MigrationReport): string {
  const lines: string[] = [];

  lines.push("# notoob Migration Report");
  lines.push("");
  lines.push(`**Mode**: ${report.execution.mode}`);
  lines.push(`**Time**: ${report.summary.totalTimeMs}ms`);
  lines.push(`**Files written**: ${report.execution.filesWritten}`);
  lines.push("");

  lines.push("## Summary");
  lines.push("");
  lines.push(`| Type | Count |`);
  lines.push(`|------|-------|`);
  lines.push(`| Pages | ${report.summary.pages} |`);
  lines.push(`| Databases | ${report.summary.databases} |`);
  lines.push(`| Database Rows | ${report.summary.databaseRows} |`);
  lines.push(`| Attachments | ${report.summary.attachments} |`);
  lines.push("");

  if (report.degradations.length > 0) {
    lines.push("## Degradations");
    lines.push("");
    lines.push("| Tag | Severity | Count | Samples |");
    lines.push("|-----|----------|-------|---------|");
    for (const d of report.degradations) {
      lines.push(
        `| ${d.tag} | ${d.severity} | ${d.count} | ${d.samples.join(", ")} |`,
      );
    }
    lines.push("");
  }

  if (report.unresolvedLinks.length > 0) {
    lines.push("## Unresolved Links");
    lines.push("");
    for (const link of report.unresolvedLinks) {
      lines.push(`- \`${link.href}\` in ${link.context} (${link.reason})`);
    }
    lines.push("");
  }

  lines.push("---");
  lines.push("*Generated by notoob*");
  lines.push("");

  return lines.join("\n");
}
